  <div class="n-crit"><div class="icon">🔴</div><div class="body"><strong>EXAM QUESTION:</strong> Q: Factors capacitance depends on? Why capacitor-start has higher torque than split-phase? - <em>Asked 4+ times.</em></div></div>

