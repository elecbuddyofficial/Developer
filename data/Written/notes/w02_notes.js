  <div class="n-card">
    <ul class="n-list">
      <li><strong>True Power (P):</strong> ACTUAL power converted into useful work. Unit: <strong>kW</strong>. Formula: <strong>P = V × I × cos(φ)</strong>.</li>
      <li><strong>Apparent Power (S):</strong> TOTAL power supplied. Unit: <strong>kVA</strong>. Formula: <strong>S = V × I</strong>. Alternators are RATED in kVA because capacity is limited by total current.</li>
      <li><strong>Power Factor (cos φ):</strong> Ratio of True to Apparent power (<strong>P/S</strong>). Range <span class="n-val">0 to 1</span>. <strong>Low PF:</strong> Alternator supplies more current for same useful power, causing I²R heat losses.</li>
    </ul>
  </div>

