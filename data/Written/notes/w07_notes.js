    <div class="n-card">
      <div class="card-title">Before Entering</div>
      <ul class="n-list" style="margin-top:8px">
        <li>Never enter alone - always in pairs minimum.</li>
        <li>Don BA set (Breathing Apparatus) - essential.</li>
        <li>Wear full firefighting gear - protective clothing, gloves, helmet.</li>
        <li>Carry a lifeline - connect to team member and fixed point outside.</li>
        <li>Carry a torch - visibility near zero in smoke.</li>
        <li>Brief the team - assign search areas, agree communication signals.</li>
        <li>Safety officer stationed outside - monitors time, holds lifeline.</li>
      </ul>
    </div>
